import type { AbilityDefinition, CardDefinition, Effect, StatusKind } from '../../engine/types.js';

const hit = (amount: number, repeat?: { min: number; max: number }): Effect => ({
  kind: 'damage',
  amount,
  ...(repeat ? { repeat } : {}),
});

const shield = (amount: number, recipient?: 'self'): Effect => ({
  kind: 'shield',
  amount,
  ...(recipient ? { recipient } : {}),
});

const heal = (amount: number, recipient?: 'self'): Effect => ({
  kind: 'heal',
  amount,
  ...(recipient ? { recipient } : {}),
});

const status = (
  kind: StatusKind,
  label: string,
  duration: number,
  value?: number,
  recipient?: 'self',
): Effect => ({
  kind: 'status',
  status: { kind, label, duration, ...(value === undefined ? {} : { value }) },
  ...(recipient ? { recipient } : {}),
});

const move = (
  id: string,
  name: string,
  description: string,
  effects: Effect[],
  options: Partial<Pick<AbilityDefinition, 'target' | 'priority' | 'cooldown' | 'availableFromRound' | 'oncePerMatch'>> = {},
): AbilityDefinition => ({
  id,
  name,
  description,
  target: options.target ?? 'enemy',
  priority: options.priority ?? 2,
  cooldown: options.cooldown ?? 0,
  ...(options.availableFromRound ? { availableFromRound: options.availableFromRound } : {}),
  ...(options.oncePerMatch ? { oncePerMatch: true } : {}),
  effects,
});

